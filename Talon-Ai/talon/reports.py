"""Documents the platform writes: candidate dossier (printable HTML), message drafts,
interview guide. Templates first; an AI model (if connected) can polish the wording."""
import html

from . import db, llm, orchestrator as orch, views

e = html.escape

CSS = """body{font-family:'Segoe UI',Arial,sans-serif;color:#10243e;max-width:860px;margin:30px auto;padding:0 24px;line-height:1.5}
h1{color:#0b3a6e;margin:0}h2{color:#0078d4;border-bottom:2px solid #dbeafe;padding-bottom:4px;margin-top:26px}
.sub{color:#5b7a99}.pill{display:inline-block;padding:2px 10px;border-radius:99px;background:#e6f1fb;color:#0b3a6e;font-size:12px;margin:2px}
.red{background:#fdecea;color:#b3261e}.green{background:#e8f5e9;color:#1b6e2d}
table{border-collapse:collapse;width:100%;font-size:13px}td,th{border:1px solid #cfe0f3;padding:6px 8px;text-align:left}th{background:#eef5fd}
.box{background:#f3f8fd;border-left:4px solid #0078d4;padding:10px 14px;border-radius:6px}
.foot{margin-top:30px;color:#7a93ab;font-size:12px}@media print{.noprint{display:none}}"""


def dossier_html(cid: int) -> str:
    v = views.case_view(cid)
    s, r, rec = v["skills"], v["readiness"] or {}, v["recommendation"] or {}
    def pills(items, cls=""):
        return "".join(f'<span class="pill {cls}">{e(str(i))}</span>' for i in items) or "-"
    out = [f"<!doctype html><html><head><meta charset='utf-8'><title>Dossier - {e(v['name'])}</title>"
           f"<style>{CSS}</style></head><body>",
           "<p class='noprint'><a href='#' onclick='window.print();return false'>Print or save as PDF</a></p>",
           f"<h1>Candidate dossier: {e(v['name'])}</h1>",
           f"<p class='sub'>{e(v['job']['title'])} &middot; {e(v['email'])} &middot; current stage: {e(v['stage'])}</p>"]
    if v["report"]:
        out.append(f"<h2>Executive summary</h2><div class='box'>{e(v['report'].get('summary', ''))}</div>")
    out.append("<h2>Decision snapshot</h2><table>"
               f"<tr><th>Match score</th><td>{e(str(v['match']))} (rank {e(str(v['rank']))} of {e(str(v['of']))})</td></tr>"
               f"<tr><th>Readiness</th><td>{e(str(r.get('score', '-')))} - {e(str(r.get('level', '-')))}</td></tr>"
               f"<tr><th>Recommendation</th><td>{e(str(rec.get('hiring', '-')))}</td></tr>"
               f"<tr><th>Deployment</th><td>{e(str(rec.get('deployment', '-')))}</td></tr>"
               f"<tr><th>Upskilling</th><td>{e(str(rec.get('upskilling', '-')))}</td></tr></table>")
    out.append(f"<h2>Skills</h2><p>Matched required: {pills(s['matched_required'], 'green')}</p>"
               f"<p>Missing: {pills(s['missing'], 'red')}</p><p>Nice-to-have matched: {pills(s['matched_nice'])}</p>")
    if v["plan"]:
        out.append("<h2>Learning plan</h2><table><tr><th>Skill</th><th>Course</th><th>Hours</th><th>Source</th></tr>" +
                   "".join(f"<tr><td>{e(p['skill'])}</td><td>{e(p['course'])}</td><td>{p['hours']}</td><td>{e(p.get('source', ''))}</td></tr>" for p in v["plan"]) + "</table>")
    sc = v["scores"]
    if sc:
        out.append("<h2>Assessment</h2><table><tr><th>Skill</th><th>Score %</th></tr>" +
                   "".join(f"<tr><td>{e(k)}</td><td>{x}</td></tr>" for k, x in sc.get("per_skill", {}).items()) +
                   f"<tr><th>Overall</th><th>{sc.get('total')}</th></tr></table>")
        flags = (v["integrity"] or {}).get("violations", [])
        out.append("<p>Integrity: " + (pills(flags, "red") if flags else "<span class='pill green'>no flags</span>") + "</p>")
    out.append("<h2>What each agent concluded</h2>")
    for a in v["agents"]:
        if a["summary"]:
            out.append(f"<p><b>{e(a['id'])}</b> ({e(a['title'])}): {e(a['summary'])}</p>")
    if rec.get("policy_evidence"):
        out.append("<h2>Policy evidence</h2>" + "".join(f"<div class='box'><b>{e(p['doc'])}</b><br>{e(p['text'])}</div><br>" for p in rec["policy_evidence"]))
    out.append("<h2>Human approvals</h2><table><tr><th>Step</th><th>Role</th><th>Status</th><th>Decided by</th><th>Comment</th><th>When</th></tr>" +
               "".join(f"<tr><td>{e(a['agent'])}</td><td>{e(a['role'])}</td><td>{e(a['status'])}</td><td>{e(str(a['decided_by'] or ''))}</td><td>{e(str(a['comment'] or ''))}</td><td>{e(str(a['decided'] or ''))}</td></tr>" for a in v["approvals"]) + "</table>")
    out.append("<p class='foot'>Generated by TALON AI. AI prepares and explains; people approve and decide. "
               "Prototype data is synthetic.</p></body></html>")
    return "".join(out)


def interview_guide(cid: int) -> list:
    v = views.case_view(cid)
    weak = [k for k, x in (v["scores"] or {}).get("per_skill", {}).items() if x < 70] or v["skills"]["missing"]
    qs = [f"Walk me through a recent project where you used {k}. What would you do differently?" for k in weak[:4]]
    qs += ["Tell me about a time your analysis was challenged. How did you respond?",
           "How do you check that data is correct before presenting it?"]
    flags = (v["integrity"] or {}).get("violations", [])
    if flags:
        qs.append("Ask the candidate to re-solve one assessment question live (an integrity flag was raised).")
    return qs


def draft_message(cid: int, kind: str = "feedback") -> str:
    v = views.case_view(cid)
    name = v["name"].split()[0]
    strong = [k for k, x in (v["scores"] or {}).get("per_skill", {}).items() if x >= 70]
    weak = [p["skill"] for p in v["plan"]][:3]
    role = v["job"]["title"]
    if kind == "invite":
        text = (f"Subject: Interview for {role}\n\nHi {name},\n\nThank you for completing the assessment. "
                f"We would like to invite you to an interview for the {role} role. Please reply with "
                "your availability for the coming week.\n\nBest regards,\nTalent Acquisition Team")
    elif kind == "brief":
        r = v["readiness"] or {}
        text = (f"Hiring manager brief: {v['name']} for {role}\n\nReadiness: {r.get('score', '-')} "
                f"({r.get('level', '-')}). Strengths: {', '.join(strong) or 'n/a'}. Gaps: "
                f"{', '.join(weak) or 'none'}.\nRecommendation: "
                f"{(v['recommendation'] or {}).get('hiring', 'pending')}.\nSuggested interview focus: "
                + "; ".join(interview_guide(cid)[:2]))
    else:
        text = (f"Subject: Your {role} application - feedback\n\nHi {name},\n\nThank you for taking part. "
                f"Your strengths: {', '.join(strong) or 'a solid foundation'}. To grow further we suggest: "
                f"{', '.join(weak) or 'continue building on your current skills'}. A learning plan with free "
                "resources is available.\n\nBest regards,\nTalent Acquisition Team")
    if llm.available():
        out = llm.chat_json("OMNIVIEW", 'Polish this message to be warm, clear and concise. Keep every fact. '
                            'Reply JSON {"text": "..."}', text, 500)
        if out and isinstance(out.get("text"), str) and 40 < len(out["text"]) < 2500:
            return out["text"]
    return text
